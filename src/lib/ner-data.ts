export function pointOnPath(path: [number, number][], t: number): [number, number] {
  const p = Math.max(0, Math.min(0.999, t));
  const segs = path.length - 1;
  const f = p * segs;
  const i = Math.floor(f);
  const u = f - i;
  const a = path[i];
  const b = path[i + 1];
  return [a[0] + (b[0] - a[0]) * u, a[1] + (b[1] - a[1]) * u];
}
